/**
 * Builds the whiteboard icon catalogue from Lucide.
 *
 * Asking a language model to invent SVG path geometry does not work. It
 * produces a puddle where a brain should be, and no amount of prompting fixes
 * that, because drawing is not what it does. Lucide is ~1600 icons drawn by
 * people at one weight on one grid -- which is also, conveniently, exactly the
 * shape our renderer wants: open stroke paths a marker can be animated along.
 *
 * Geometry is kept in Lucide's own 24x24 space. The scene composer already
 * scales path data properly (arc flags and all), so it only needs to be told
 * the box is 24 rather than 100.
 *
 * Run: node scripts/build-icon-catalogue.mjs
 */

import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";

const ICON_DIR = path.resolve("node_modules/lucide-react/dist/esm/icons");
const OUT = path.resolve("src/lib/whiteboard/icon-paths.generated.ts");

const round = (n) => Math.round(n * 100) / 100;

/** Every Lucide primitive, expressed as path data. */
function toPath([tag, attrs]) {
  const num = (key, fallback = 0) => {
    const value = Number.parseFloat(attrs[key]);
    return Number.isFinite(value) ? value : fallback;
  };

  switch (tag) {
    case "path":
      return typeof attrs.d === "string" ? attrs.d : null;

    case "line":
      return `M ${round(num("x1"))} ${round(num("y1"))} L ${round(num("x2"))} ${round(num("y2"))}`;

    case "circle": {
      const cx = num("cx");
      const cy = num("cy");
      const r = num("r");
      if (r <= 0) return null;
      // Two half-arcs: one arc command cannot close a full circle.
      return `M ${round(cx - r)} ${round(cy)} A ${round(r)} ${round(r)} 0 1 0 ${round(cx + r)} ${round(cy)} A ${round(r)} ${round(r)} 0 1 0 ${round(cx - r)} ${round(cy)} Z`;
    }

    case "ellipse": {
      const cx = num("cx");
      const cy = num("cy");
      const rx = num("rx");
      const ry = num("ry");
      if (rx <= 0 || ry <= 0) return null;
      return `M ${round(cx - rx)} ${round(cy)} A ${round(rx)} ${round(ry)} 0 1 0 ${round(cx + rx)} ${round(cy)} A ${round(rx)} ${round(ry)} 0 1 0 ${round(cx - rx)} ${round(cy)} Z`;
    }

    case "rect": {
      const x = num("x");
      const y = num("y");
      const w = num("width");
      const h = num("height");
      const r = Math.min(num("rx", 0) || num("ry", 0), w / 2, h / 2);
      if (w <= 0 || h <= 0) return null;
      if (r <= 0) {
        return `M ${round(x)} ${round(y)} L ${round(x + w)} ${round(y)} L ${round(x + w)} ${round(y + h)} L ${round(x)} ${round(y + h)} Z`;
      }
      return [
        `M ${round(x + r)} ${round(y)}`,
        `L ${round(x + w - r)} ${round(y)}`,
        `A ${round(r)} ${round(r)} 0 0 1 ${round(x + w)} ${round(y + r)}`,
        `L ${round(x + w)} ${round(y + h - r)}`,
        `A ${round(r)} ${round(r)} 0 0 1 ${round(x + w - r)} ${round(y + h)}`,
        `L ${round(x + r)} ${round(y + h)}`,
        `A ${round(r)} ${round(r)} 0 0 1 ${round(x)} ${round(y + h - r)}`,
        `L ${round(x)} ${round(y + r)}`,
        `A ${round(r)} ${round(r)} 0 0 1 ${round(x + r)} ${round(y)}`,
        "Z",
      ].join(" ");
    }

    case "polyline":
    case "polygon": {
      const points = String(attrs.points ?? "")
        .trim()
        .split(/[\s,]+/)
        .map(Number)
        .filter(Number.isFinite);
      if (points.length < 4) return null;
      const parts = [`M ${round(points[0])} ${round(points[1])}`];
      for (let i = 2; i < points.length - 1; i += 2) {
        parts.push(`L ${round(points[i])} ${round(points[i + 1])}`);
      }
      if (tag === "polygon") parts.push("Z");
      return parts.join(" ");
    }

    default:
      return null;
  }
}

const files = (await readdir(ICON_DIR)).filter(
  (name) => name.endsWith(".mjs") && !name.endsWith(".map"),
);

const catalogue = {};
let skipped = 0;

for (const file of files) {
  const name = file.replace(/\.mjs$/, "");
  try {
    const iconMod = await import(pathToFileURL(path.join(ICON_DIR, file)).href);
    const nodes = iconMod.__iconNode;
    if (!Array.isArray(nodes)) {
      skipped += 1;
      continue;
    }
    const paths = nodes.map(toPath).filter((d) => typeof d === "string" && d.length > 0);
    if (paths.length) catalogue[name] = paths;
    else skipped += 1;
  } catch {
    skipped += 1;
  }
}

const names = Object.keys(catalogue).sort();
const body = names.map((name) => `  ${JSON.stringify(name)}: ${JSON.stringify(catalogue[name])},`);

const source = `/**
 * Generated by scripts/build-icon-catalogue.mjs -- do not edit.
 *
 * Lucide icon geometry in Lucide's own 24x24 space, as path data.
 * ${names.length} icons, ISC licensed (see node_modules/lucide-react/LICENSE).
 */

export const ICON_VIEWBOX = 24;

export const LUCIDE_PATHS: Record<string, string[]> = {
${body.join("\n")}
};

export const LUCIDE_NAMES: string[] = Object.keys(LUCIDE_PATHS);
`;

await writeFile(OUT, source, "utf8");
console.log(`wrote ${names.length} icons to ${path.relative(process.cwd(), OUT)} (skipped ${skipped})`);
